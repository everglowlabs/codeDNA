// Compiler defines the interface for translating DNA_Schema into target formats.
type Compiler interface {
	Compile(dna schema.DNA_Schema) (map[string]string, error)
}

// CursorCompiler exports rules for Cursor / Antigravity (.cursorrules)
type CursorCompiler struct{}

func (c *CursorCompiler) Compile(dna schema.DNA_Schema) (map[string]string, error) {
	outputs := make(map[string]string)

	for _, s := range dna.Standards {
		var sb strings.Builder

		// Determine globs from samples
		globMap := make(map[string]bool)
		for _, sample := range s.Samples {
			dir := filepath.Dir(sample.FilePath)
			ext := filepath.Ext(sample.FilePath)
			if dir == "." {
				globMap["*"+ext] = true
			} else {
				globMap[dir+"/**/*"+ext] = true
			}
		}

		var globs []string
		for g := range globMap {
			globs = append(globs, g)
		}

		// YAML Frontmatter
		sb.WriteString("---\n")
		sb.WriteString(fmt.Sprintf("description: %s\n", s.Description))
		sb.WriteString("globs: ")
		if len(globs) == 0 {
			sb.WriteString("**/*")
		} else {
			sb.WriteString(strings.Join(globs, ", "))
		}
		sb.WriteString("\n")
		sb.WriteString("alwaysApply: false\n")
		sb.WriteString("---\n\n")

		sb.WriteString("# " + s.Title + "\n\n")
		sb.WriteString(s.Description + "\n\n")
		sb.WriteString("## Guidelines\n")
		for _, rule := range s.Rules {
			sb.WriteString(fmt.Sprintf("- %s\n", rule))
		}

		filename := sanitizeFilename(s.Title)
		fullPath := fmt.Sprintf(".cursor/rules/%s.mdc", filename)
		outputs[fullPath] = sb.String()
	}

	return outputs, nil
}

