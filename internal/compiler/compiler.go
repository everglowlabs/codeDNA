// MarkdownCompiler exports human-readable standards
type MarkdownCompiler struct{}

func (c *MarkdownCompiler) Compile(dna schema.DNA_Schema) (map[string]string, error) {
	var sb strings.Builder
	sb.WriteString(fmt.Sprintf("# %s: Engineering Standards\n\n", dna.ProjectName))
	sb.WriteString(fmt.Sprintf("*Generated by CodeDNA on %s*\n\n", dna.GeneratedAt.Format("2006-01-02")))

	for _, s := range dna.Standards {
		sb.WriteString(fmt.Sprintf("## %s\n", s.Title))
		sb.WriteString(fmt.Sprintf("> %s\n\n", s.Rationale))
		sb.WriteString("### Patterns Detected\n")
		for _, p := range s.Patterns {
			sb.WriteString(fmt.Sprintf("- `%s`\n", p))
		}
		sb.WriteString("\n### Guidelines\n")
		for _, rule := range s.Rules {
			sb.WriteString(fmt.Sprintf("- %s\n", rule))
		}
		sb.WriteString("\n---\n\n")
	}

	return map[string]string{
		"CODEDNA_STANDARDS.md": sb.String(),
	}, nil
}

// JSONCompiler exports the raw DNA schema
type JSONCompiler struct{}

func (c *JSONCompiler) Compile(dna schema.DNA_Schema) (map[string]string, error) {
	data, err := json.MarshalIndent(dna, "", "  ")
	if err != nil {
		return nil, err
	}
	return map[string]string{
		"codedna.json": string(data),
	}, nil
}

// AntigravityCompiler exports modular rules for Antigravity (.agents/rules/*.md)
type AntigravityCompiler struct{}

func (c *AntigravityCompiler) Compile(dna schema.DNA_Schema) (map[string]string, error) {
	outputs := make(map[string]string)

	for _, s := range dna.Standards {
		var sb strings.Builder
		sb.WriteString(fmt.Sprintf("# %s\n\n", s.Title))
		sb.WriteString(fmt.Sprintf("Category: %s\n", s.Category))
		sb.WriteString(fmt.Sprintf("Rationale: %s\n\n", s.Rationale))
		sb.WriteString("## Guidelines\n")
		for _, rule := range s.Rules {
			sb.WriteString(fmt.Sprintf("- %s\n", rule))
		}

		if len(s.Samples) > 0 {
			sb.WriteString("\n## Examples\n")
			for _, sample := range s.Samples {
				sb.WriteString(fmt.Sprintf("```%s\n// File: %s\n%s\n```\n\n", sample.Language, sample.FilePath, sample.Content))
			}
		}

		// Sanitize title for filename
		filename := strings.ToLower(s.Title)
		filename = strings.ReplaceAll(filename, " ", "_")
		filename = strings.ReplaceAll(filename, "/", "_")
		fullPath := fmt.Sprintf(".agents/rules/%s.md", filename)

		content := sb.String()
		// Limit to 12,000 chars as per Antigravity docs
		if len(content) > 12000 {
			content = content[:11997] + "..."
		}

		outputs[fullPath] = content
	}

	return outputs, nil
}

// ClaudeCompiler exports rules for Claude Dev / Continue.dev (CLAUDE.md)
type ClaudeCompiler struct{}

func (c *ClaudeCompiler) Compile(dna schema.DNA_Schema) (map[string]string, error) {
	outputs := make(map[string]string)

	// 1. Generate Lean CLAUDE.md
	var mainSb strings.Builder
	mainSb.WriteString("# " + dna.ProjectName + "\n\n")
	mainSb.WriteString("## Project Summary\n")
	mainSb.WriteString("Engineering standards and patterns extracted by CodeDNA.\n\n")
	mainSb.WriteString("## Standards Overview\n")
	for _, s := range dna.Standards {
		mainSb.WriteString(fmt.Sprintf("- [%s](.claude/rules/%s.md): %s\n", s.Title, sanitizeFilename(s.Title), s.Description))
	}
	outputs["CLAUDE.md"] = mainSb.String()

	// 2. Generate Modular Rules
	for _, s := range dna.Standards {
		var sb strings.Builder

		// Determine paths from samples
		pathMap := make(map[string]bool)
		for _, sample := range s.Samples {
			dir := filepath.Dir(sample.FilePath)
			ext := filepath.Ext(sample.FilePath)
			if dir == "." {
				pathMap["*"+ext] = true
			} else {
				pathMap[dir+"/**/*"+ext] = true
			}
		}

		var paths []string
		for p := range pathMap {
			paths = append(paths, p)
		}

		// YAML Frontmatter (Claude uses 'paths')
		sb.WriteString("---\n")
		sb.WriteString("paths:\n")
		if len(paths) == 0 {
			sb.WriteString("  - \"**/*\"\n")
		} else {
			for _, p := range paths {
				sb.WriteString(fmt.Sprintf("  - \"%s\"\n", p))
			}
		}
		sb.WriteString("---\n\n")

		sb.WriteString("# " + s.Title + "\n\n")
		sb.WriteString(s.Description + "\n\n")
		sb.WriteString("## Guidelines\n")
		for _, rule := range s.Rules {
			sb.WriteString(fmt.Sprintf("- %s\n", rule))
		}

		filename := sanitizeFilename(s.Title)
		fullPath := fmt.Sprintf(".claude/rules/%s.md", filename)
		outputs[fullPath] = sb.String()
	}

	return outputs, nil
}

// Helper to sanitize filenames
func sanitizeFilename(s string) string {
	res := strings.ToLower(s)
	res = strings.ReplaceAll(res, " ", "_")
	res = strings.ReplaceAll(res, "/", "_")
	return res
}

